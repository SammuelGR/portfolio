import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = path.join(rootDir, 'src', 'locales');
const canonicalLanguage = 'en-US';
const supportedLanguages = ['en-US', 'pt-BR'];
const namespace = 'translation';

function sortKeys(value) {
  if (Array.isArray(value) || value === null || typeof value !== 'object') {
    return value;
  }

  return Object.fromEntries(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)));
}

async function readTranslations(language) {
  const filePath = path.join(localesDir, language, 'translations.json');
  const file = await readFile(filePath, 'utf8');

  return JSON.parse(file);
}

function collectKeyPaths(value, prefix = '') {
  if (value === null || Array.isArray(value) || typeof value !== 'object') {
    return [prefix];
  }

  return Object.entries(value).flatMap(([key, childValue]) =>
    collectKeyPaths(childValue, prefix ? `${prefix}.${key}` : key),
  );
}

function assertMatchingKeys(canonicalTranslations, language, translations) {
  const canonicalKeys = collectKeyPaths(canonicalTranslations).sort();
  const languageKeys = collectKeyPaths(translations).sort();
  const missingKeys = canonicalKeys.filter((key) => !languageKeys.includes(key));
  const extraKeys = languageKeys.filter((key) => !canonicalKeys.includes(key));

  if (missingKeys.length === 0 && extraKeys.length === 0) {
    return;
  }

  const details = [
    missingKeys.length > 0 ? `Missing keys: ${missingKeys.join(', ')}` : null,
    extraKeys.length > 0 ? `Extra keys: ${extraKeys.join(', ')}` : null,
  ]
    .filter(Boolean)
    .join('\n');

  throw new Error(`${language} translations do not match ${canonicalLanguage}.\n${details}`);
}

function toPropertyKey(key) {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function toStringLiteral(value) {
  return `'${value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')}'`;
}

function toTypeLiteral(value, indentLevel = 1) {
  const indent = '  '.repeat(indentLevel);
  const nextIndent = '  '.repeat(indentLevel + 1);

  if (typeof value === 'string') {
    return toStringLiteral(value);
  }

  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }

  if (value === null) {
    return 'null';
  }

  if (Array.isArray(value)) {
    const itemTypes = [...new Set(value.map((item) => toTypeLiteral(item, indentLevel)))];

    return itemTypes.length > 0 ? `Array<${itemTypes.join(' | ')}>` : 'unknown[]';
  }

  const entries = Object.entries(sortKeys(value));

  if (entries.length === 0) {
    return '{}';
  }

  const lines = entries.map(
    ([key, childValue]) => `${nextIndent}${toPropertyKey(key)}: ${toTypeLiteral(childValue, indentLevel + 1)};`,
  );

  return `{\n${lines.join('\n')}\n${indent}}`;
}

const canonicalTranslations = await readTranslations(canonicalLanguage);

for (const language of supportedLanguages) {
  if (language === canonicalLanguage) {
    continue;
  }

  assertMatchingKeys(canonicalTranslations, language, await readTranslations(language));
}

const output = `// This file is generated by scripts/generate-i18n-types.mjs.
// Do not edit it manually.

export type Resources = {
  ${namespace}: ${toTypeLiteral(canonicalTranslations)};
};
`;

await writeFile(path.join(rootDir, 'src', '@types', 'resources.d.ts'), output);
